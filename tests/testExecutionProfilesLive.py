"""The execution profiles' settings are really requested, in real containers.

A generic linear-algebra fixture -- seeded matrices and vectors, a
product, a solve, an eigendecomposition, vectorised ``exp`` and
``log`` -- is regenerated by a project's own ``reproduce.sh`` against a
real daemon, in an image whose NumPy carries its bundled OpenBLAS:

* under ``across-v1`` the fixture's digest is the one COMMITTED here,
  measured on an ``x86-64-v4`` machine, so every runner that reproduces
  it is cross-machine evidence (design 0e). The runner's processor is
  printed beside the result, because evidence about a machine nobody
  named is not evidence. The run's own probe record is read first: the
  settings reached the container and NumPy applied each one, so a
  differing digest means the profile did not suffice, not that it was
  never in force;
* a NumPy older than 2.4 does not know ``X86_V4`` and ignores it behind
  a warning Python hides, and the probe says so (design F7). On an
  AVX-512 machine such a NumPy keeps dispatching AVX-512 under
  ``across-v1``, which is why the fixture's image carries a NumPy that
  knows the name;
* under ``across-v1`` two visible cores give the same bytes as every
  core, because one thread is requested;
* under ``speed-v1`` they do not, because OpenBLAS follows the cores it
  can see (design fact 18). This half needs a daemon with at least four
  cores, and says so when it cannot run.

The image is obtained as ``tests/testReproduceScriptParityLive.py``
obtains it: a ``docker`` stand-in maps the envelope's pinned reference
to the image built here, and a ``curl`` stand-in refuses every fetch.
Every command of the container half, the profile's validation, the
capability reading and the probe included, runs for real.

Skipped automatically when no daemon is reachable, unless
``VAIBIFY_REQUIRE_DOCKER_DAEMON`` demands one.
"""

