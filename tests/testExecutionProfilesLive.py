def _fiterBuildImage(sNumpyVersion, sTag):
    """Yield one built image's facts; remove the image afterwards."""
    fnRequireDaemonReachable()
    dockerDisposable = disposableContainer.fdockerCreateDisposableClient()
    imageProbe = _fimageBuildProbeImage(
        dockerDisposable, _S_PROFILE_DOCKERFILE_TEMPLATE.format(
            sNumpyVersion=sNumpyVersion), sTag)
    try:
        yield {
            "sImageId": imageProbe.id,
            "sNumpyVersion": sNumpyVersion,
            "sArchitecture": str(imageProbe.attrs.get("Architecture") or ""),
            "iDaemonCores": int(dockerDisposable.info().get("NCPU") or 0),
        }
    finally:
        try:
            dockerDisposable.images.remove(imageProbe.id, force=True)
        except Exception:  # noqa: BLE001 -- cleanup only
            pass


def _fsPublishTheFixture(sRoot, dictImage, dictRecordedProfile):
    """Lay out the fixture project; return its root."""
    os.makedirs(sRoot)
    fnWriteText(sRoot, f"{S_STEP}/fixture.py", _S_FIXTURE_PROGRAM)
    fnWriteText(sRoot, f"{S_STEP}/{S_DIGEST_FILE}",
                S_ACROSS_FIXTURE_DIGEST + "\n")
    fnWriteText(sRoot, "requirements.lock", "")
    dictEnvelope = {"dictContainer": {
        "sImageDigest": S_UNSERVED_REFERENCE,
        "sArchitecture": dictImage["sArchitecture"]}}
    if dictRecordedProfile is not None:
        dictEnvelope["dictExecutionProfile"] = dictRecordedProfile
    fnWriteText(sRoot, ".vaibify/environment.json", json.dumps(dictEnvelope))
    dictWorkflow = fdictBuildWorkflow([fdictBuildStep(
        "Fixture", S_STEP, saDataCommands=["python3 fixture.py"],
        saOutputDataFiles=[S_DIGEST_FILE])])
    for sRelative, sText in ftRenderReproductionFiles(dictWorkflow):
        if sRelative == S_REPRODUCE_SCRIPT_FILENAME:
            sText = fsKeepRunDirectories(
                sText, f"{S_REPRODUCTION_REPO_ROOT}/{S_KEPT_DIRECTORY}")
        fnWriteText(sRoot, sRelative, sText)
    os.makedirs(os.path.join(sRoot, S_KEPT_DIRECTORY))
    fnWriteManifest(sRoot, [f"{S_STEP}/fixture.py", f"{S_STEP}/{S_DIGEST_FILE}"])
    return sRoot


def _fdictReadKeptProbe(sRoot):
    """Return the probe record the run wrote into its scratch, or {}."""
    listPaths = glob.glob(os.path.join(
        sRoot, S_KEPT_DIRECTORY, "vaibifyScratch.*",
        rerunProcedure.S_PROBE_RECORD_FILENAME))
    if not listPaths:
        return {}
    with open(listPaths[0], encoding="utf-8") as fileIn:
        return json.load(fileIn)


def _ftReproduce(tmp_path, sName, dictImage, dictRecordedProfile,
                 listRunArguments=()):
    """Run a fresh copy of the fixture's reproduce.sh.

    Returns the completed process, the digest it regenerated and the
    probe record its own run kept.
    """
    sRoot = _fsPublishTheFixture(
        str(tmp_path / sName), dictImage, dictRecordedProfile)
    if not _fbBindMountReachesTheDaemon(pathlib.Path(sRoot)):
        pytest.skip("the daemon cannot see " + sRoot + " through a bind "
                    "mount; run with a temporary directory inside a "
                    "shared path")
    _fnLetTheImagesUserWrite(sRoot)
    sBin = str(tmp_path / (sName + "StandIns"))
    _fnInstallImageStandIns(sBin, dictImage["sImageId"], listRunArguments)
    dictEnvironment = dict(os.environ)
    dictEnvironment["PATH"] = sBin + os.pathsep + dictEnvironment["PATH"]
    completed = subprocess.run(
        ["bash", S_REPRODUCE_SCRIPT_FILENAME], cwd=sRoot, env=dictEnvironment,
        capture_output=True, text=True, timeout=900)
    sPath = os.path.join(sRoot, S_STEP, S_DIGEST_FILE)
    sDigest = open(sPath).read().strip() if os.path.isfile(sPath) else ""
    return completed, sDigest, _fdictReadKeptProbe(sRoot)


# Run in one container when the fixture's digest is wrong: the fixture
# under every setting, without each one in turn, and under none, so a
# failure on a machine nobody here can reach names the setting at fault.
# A crash names the innermost Python frame it died in (faulthandler),
# and the kernel OpenBLAS chose is read under each variant. The first
# line summarizes every variant, because the falsification lane keeps
# only the start of a failure message.
_S_DIAGNOSIS_PROGRAM = """import json, os, re, subprocess, sys
dictRequested = json.loads(sys.argv[1])
os.makedirs("/tmp/fixture", exist_ok=True)
open("/tmp/fixture/fixture.py", "w").write(sys.argv[2])
sCoreProgram = (
    "import ctypes, glob, os, numpy\\n"
    "s = os.path.dirname(os.path.dirname(numpy.__file__))\\n"
    "l = ctypes.CDLL(sorted(glob.glob(s + '/numpy.libs/*openblas*'))[0])\\n"
    "f = getattr(l, 'scipy_openblas_get_corename64_', None) or "
    "getattr(l, 'openblas_get_corename64_')\\n"
    "f.restype = ctypes.c_char_p\\n"
    "g = getattr(l, 'scipy_openblas_get_config64_', None) or "
    "getattr(l, 'openblas_get_config64_')\\n"
    "g.restype = ctypes.c_char_p\\n"
    "print(numpy.__version__, f().decode(), g().decode())\\n")
listVariants = [("every setting", dictRequested)] + [
    ("without " + sKey, {k: v for k, v in dictRequested.items() if k != sKey})
    for sKey in dictRequested] + [("no setting", {})]
listSummary, listDetail = [], []
for sName, dictSettings in listVariants:
    dictEnvironment = {k: v for k, v in os.environ.items()
                       if k not in dictRequested}
    dictEnvironment.update(dictSettings)
    completedCore = subprocess.run(
        [sys.executable, "-c", sCoreProgram], env=dictEnvironment,
        capture_output=True, text=True)
    completed = subprocess.run(
        [sys.executable, "-X", "faulthandler", "fixture.py"],
        env=dictEnvironment, cwd="/tmp/fixture", capture_output=True,
        text=True)
    sCore = completedCore.stdout.strip() or str(completedCore.returncode)
    if completed.returncode == 0:
        sOutcome = open("/tmp/fixture/digest.txt").read().strip()[:12]
    else:
        listFrames = re.findall(
            r'File "([^"]+)", line (\\d+) in (\\S+)', completed.stderr)
        sOutcome = "in " + (" ".join([os.path.basename(listFrames[0][0])
                                      + ":" + listFrames[0][1],
                                      listFrames[0][2]])
                            if listFrames else "no Python frame")
    listSummary.append(f"{sName}: exit {completed.returncode} {sOutcome}, "
                       f"OpenBLAS {(sCore.split() + ['?', '?'])[1]}")
    listDetail.append(f"{sName}: core {sCore}")
    if completed.returncode != 0:
        listDetail.append(
            "    " + "\\n    ".join(completed.stderr.splitlines()[-12:]))
print("; ".join(listSummary))
print("\\n".join(listDetail))
"""


def _fsDiagnoseEachSetting(listImages, dictRequested):
    """Return the fixture's outcome under each variant, in each image."""
    dockerDisposable = disposableContainer.fdockerCreateDisposableClient()
    listSummaries, listDetails = [], []
    for dictImage in listImages:
        baOutput = dockerDisposable.containers.run(
            dictImage["sImageId"],
            ["python3", "-c", _S_DIAGNOSIS_PROGRAM, json.dumps(dictRequested),
             _S_FIXTURE_PROGRAM],
            network_disabled=True, labels=fdictLabels(), remove=True,
            stdout=True, stderr=True)
        sSummary, _, sDetail = baOutput.decode(
            "utf-8", "replace").partition("\n")
        sLabel = f"NumPy {dictImage['sNumpyVersion']}"
        listSummaries.append(f"Each setting in turn, {sLabel}: {sSummary}")
        listDetails.append(f"{sLabel} in detail:\n{sDetail}")
    return "\n".join(listSummaries + listDetails) + "\n"


def _fsDescribeThisMachine(dictImage):
    """Return the processor facts the record keeps: vendor, level, cores."""
    dictCapabilities = rerunProcedure.fdictReadProcessorCapabilities()
    return (f"vendor {dictCapabilities['sVendor']}, level "
            f"{dictCapabilities['sLevel']}, daemon cores "
            f"{dictImage['iDaemonCores']}")


@pytest.mark.falsification
def testTheAcrossProfileReproducesTheCommittedFixture(
    dictProfileImage, dictOlderNumpyImage, tmp_path, capsys,
):
    """This runner regenerates the digest measured on another machine.

    The probe is read before the digest, so the kill does not depend on
    this runner's processor: without the profile no runner's probe sees
    the settings.

    Kills: reproduce.sh validating the recorded profile and never
    handing it to the container.
    """
    sMachine = _fsDescribeThisMachine(dictProfileImage)
    with capsys.disabled():
        print(f"\nRunner processor: {sMachine}")
    dictProfile = executionProfiles.fdictProfileFromTable(
        executionProfiles.S_PROFILE_ACROSS)
    completed, sDigest, dictProbe = _ftReproduce(
        tmp_path, "across", dictProfileImage, dictProfile)
    sOutput = completed.stdout + completed.stderr
    if sDigest != S_ACROSS_FIXTURE_DIGEST:
        sOutput = _fsDiagnoseEachSetting(
            [dictProfileImage, dictOlderNumpyImage],
            dictProfile["dictRequested"]) + sOutput
    assert dictProbe.get("dictSettingsSeen") == dictProfile["dictRequested"], (
        sMachine, dictProbe, sOutput)
    assert {sName: dictJudged["sStatus"] for sName, dictJudged in
            dictProbe["dictNumpyDisabledFeatures"].items()} == {
        "AVX512_ICL": "applied", "X86_V4": "applied"}, (sMachine, dictProbe,
                                                        sOutput)
    assert sDigest == S_ACROSS_FIXTURE_DIGEST, (sMachine, sDigest, sOutput)
    assert completed.returncode == 0, sOutput
    assert "Reproduced: every file byte-identical" in completed.stdout


@pytest.mark.falsification
def testTheAcrossProfileGivesTheSameBytesOnTwoCores(dictProfileImage, tmp_path):
    """One thread is requested, so the visible cores cannot reach the bytes.

    Kills: ``across-v1`` requesting no thread pin.
    """
    dictProfile = executionProfiles.fdictProfileFromTable(
        executionProfiles.S_PROFILE_ACROSS)
    _completedAll, sAll, _dictProbeAll = _ftReproduce(
        tmp_path, "allCores", dictProfileImage, dictProfile)
    completedTwo, sTwo, _dictProbeTwo = _ftReproduce(
        tmp_path, "twoCores", dictProfileImage, dictProfile,
        ["--cpuset-cpus", "0-1"])
    sOutput = completedTwo.stdout + completedTwo.stderr
    if not (sAll and sAll == sTwo):
        sOutput = _fsDiagnoseEachSetting(
            [dictProfileImage], dictProfile["dictRequested"]) + sOutput
    assert sAll and sAll == sTwo, sOutput


def testTheSpeedProfileFollowsTheVisibleCores(dictProfileImage, tmp_path):
    """Without a thread pin, OpenBLAS uses the cores it sees (design fact 18)."""
    if dictProfileImage["iDaemonCores"] < 4:
        pytest.skip(
            f"the daemon has {dictProfileImage['iDaemonCores']} cores; two "
            "visible cores against all of them needs at least four")
    _completedAll, sAll, _dictProbeAll = _ftReproduce(
        tmp_path, "speedAll", dictProfileImage, None)
    _completedTwo, sTwo, _dictProbeTwo = _ftReproduce(
        tmp_path, "speedTwo", dictProfileImage, None, ["--cpuset-cpus", "0-1"])
    assert sAll and sTwo and sAll != sTwo


@pytest.mark.falsification
def testANumpyOlderThanTheFeatureGroupsSaysItIgnoredOne(dictOlderNumpyImage):
    """A real NumPy 2.1.3, asked for ``across-v1``, is recorded as ignoring X86_V4.

    Kills: judging a name outside NumPy's dispatch list by whether it
    is active, which an unknown name never is.
    """
    dictProfile = executionProfiles.fdictProfileFromTable(
        executionProfiles.S_PROFILE_ACROSS)
    dockerDisposable = disposableContainer.fdockerCreateDisposableClient()
    baOutput = dockerDisposable.containers.run(
        dictOlderNumpyImage["sImageId"],
        ["python3", "-I", "-c", rerunAssessment.fsBuildProcedureProgram(),
         "probe", "--machine"],
        environment=dictProfile["dictRequested"], network_disabled=True,
        labels=fdictLabels(), remove=True, stdout=True, stderr=False)
    listRecords = [
        json.loads(sLine[len(rerunProcedure.S_PROBE_RESULT_PREFIX):])
        for sLine in baOutput.decode("utf-8", "replace").splitlines()
        if sLine.startswith(rerunProcedure.S_PROBE_RESULT_PREFIX)]
    assert len(listRecords) == 1, baOutput
    dictProbe = listRecords[0]
    assert dictProbe["sNumpyVersion"] == S_OLDER_NUMPY_VERSION
    assert dictProbe["dictNumpyDisabledFeatures"] == {
        "AVX512_ICL": {"sStatus": "applied", "sReason": ""},
        "X86_V4": {"sStatus": "not applied",
                   "sReason": "this NumPy does not know that feature name"},
    }
