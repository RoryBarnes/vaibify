"""The mutation inventory is complete, unique, current, and well-formed.

The inventory (``tests/mutationInventory.json``, generated by
``tools/generateMutationInventory.py``) is the mandatory checkpoint
before any migration onto a single mutation carrier: one row per
reference that can reach a container, so a 280-site surgery is judged
against a record rather than against whoever last read the diff.

A record that can silently fall behind the code is worse than no record,
because it reads as coverage. THE FIRST VERSION OF THIS FILE WAS THAT
RECORD. It compared the inventory against the same scanner that built
it, and that scanner recognised only a direct call -- so 24 primitives
passed as callbacks (``asyncio.to_thread(connection.fnWriteFile, ...)``)
and 25 Docker CLI invocations assembled from scratch were invisible to
both. 21 of the callbacks were mutation-capable, including the
clean-outputs deletion the whole boundary was justified by. An external
review found it; the tests below are what would have.

So the scanner is now checked ADVERSARIALLY, against synthetic sources
containing each shape it must not miss, rather than only against the
tree it was written from. A scan that agrees with itself proves nothing.
"""

import ast
import collections
import copy
import importlib.util
import pathlib
import textwrap

import pytest


PATH_REPOSITORY = pathlib.Path(__file__).resolve().parent.parent

# The number of rows still awaiting a reviewer's semantic judgement.
# This is a RATCHET: it may only ever be lowered, and lowering it means
# somebody classified those rows. Raising it means new call sites
# shipped unreviewed, which is the state this record exists to make
# visible.
#
# 291 -> 293 on 2026-08-02, and this is the one shape of increase that
# is not new debt: scoping the scanner's command-list resolution per
# FUNCTION rather than per module resolved three sites that were only
# opaque because two functions in a module each named a local
# `listCommand`. Two of them are Docker invocations in a GUI module --
# `docker stats` and a mutation-capable `docker exec` -- so they moved
# OUT of the blind spot and INTO the record, which is the direction
# this file wants. DICT_UNRESOLVED_BUDGET fell from 26 to 23 in the
# same change; read the two numbers together or this one lies.
#
# 293 -> 289 on 2026-08-02: four rows withdrawn as false resolutions
# when the scanner gained a real lexical-scope model. See
# DICT_UNRESOLVED_BUDGET, which rose by the same four.
#
# 289 -> 307 on 2026-08-03, and this rise is the redesign working rather
# than debt arriving. Completeness moved off the command decoder and onto
# the capability, so the 18 launches whose argv the scan cannot read are
# now ROWS with an UNKNOWN command instead of blind-spot entries alone.
# Every one of them was a site the record previously could only count.
# Read this with DICT_UNRESOLVED_BUDGET, which fell 26 -> 18 in the same
# change for an unrelated reason, and with
# I_UNDISPOSED_ACQUISITION_BUDGET, which is the record that is now
# completeness-critical.
I_UNCLASSIFIED_ROW_BUDGET = 307


# Every acquisition of a declared capability that still has no reviewed
# disposition. A RATCHET on the same terms as the row budget, and the one
# that carries completeness: a use site can go unrecorded because nobody
# could decode it, but an acquisition is an import or an attribute load,
# which the scan reads exactly.
#
# Seeded at 66 on 2026-08-03, the count on the day the record was
# created: 37 process-launch, 11 Docker-client, 17 reflection, 1
# Unix-socket. None of them is reviewed yet, and the number says so out
# loud rather than shipping a record that implies a review nobody did.
I_UNDISPOSED_ACQUISITION_BUDGET = 66


def _fmoduleGenerator():
    """Import the inventory generator by path (tools/ is not a package)."""
    pathTool = PATH_REPOSITORY / "tools" / "generateMutationInventory.py"
    spec = importlib.util.spec_from_file_location(
        "generateMutationInventoryUnderTest", pathTool,
    )
    moduleTool = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(moduleTool)
    return moduleTool


@pytest.fixture(scope="module")
def moduleGenerator():
    return _fmoduleGenerator()


def _flistScanSource(moduleGenerator, sSource, sPath="synthetic.py"):
    """Run the scanner over a synthetic module and return its rows."""
    visitor = moduleGenerator._VisitorCallSites(sPath)
    visitor.fnCollect(ast.parse(textwrap.dedent(sSource)))
    return visitor.listRows


def _flistScanAcquisitions(moduleGenerator, sSource, sPath="synthetic.py"):
    """Run the scanner over a synthetic module and return its acquisitions."""
    visitor = moduleGenerator._VisitorCallSites(sPath)
    visitor.fnCollect(ast.parse(textwrap.dedent(sSource)))
    return visitor.listAcquisitions


