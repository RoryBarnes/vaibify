def testTheScannerSeesAPrimitivePassedAsACallback(moduleGenerator):
    """``asyncio.to_thread(connection.fnWriteFile, ...)`` is a call site.

    The exact omission an external review found. The AST node for a
    passed bound method is an attribute LOAD, not a Call, so a scanner
    that visits Call nodes sees the ``to_thread`` and nothing else --
    and 21 mutation-capable sites, including a container-wide file
    deletion, were absent from a record that claimed completeness.
    """
    listRows = _flistScanSource(moduleGenerator, """
        async def fnCleanOutputs(connectionDocker, sContainerId, sCommand):
            await asyncio.to_thread(
                connectionDocker.ftResultExecuteCommand,
                sContainerId, sCommand,
            )
    """)
    assert len(listRows) == 1, listRows
    assert listRows[0]["sPrimitive"] == "ftResultExecuteCommand"
    assert listRows[0]["sReferenceKind"] == (
        moduleGenerator.S_REFERENCE_PASSED_CALLABLE
    )
    assert listRows[0]["bMutationCapable"] is True


def testTheScannerSeesAPrimitiveBoundToALocalName(moduleGenerator):
    """An alias is a reference, and the reference is what matters."""
    listRows = _flistScanSource(moduleGenerator, """
        def fnWriteEverything(connectionDocker, listPaths):
            fnWriter = connectionDocker.fnWriteFile
            for sPath in listPaths:
                fnWriter("cid", sPath, b"")
    """)
    listPassed = [
        dictRow for dictRow in listRows
        if dictRow["sReferenceKind"] == (
            moduleGenerator.S_REFERENCE_PASSED_CALLABLE
        )
    ]
    assert len(listPassed) == 1, listRows
    assert listPassed[0]["sPrimitive"] == "fnWriteFile"


def testADirectCallIsNotAlsoCountedAsAPassedCallable(moduleGenerator):
    """One reference, one row -- the two shapes must not overlap."""
    listRows = _flistScanSource(moduleGenerator, """
        def fnRun(connectionDocker):
            connectionDocker.ftResultExecuteCommand("cid", "true")
    """)
    assert len(listRows) == 1, listRows
    assert listRows[0]["sReferenceKind"] == (
        moduleGenerator.S_REFERENCE_DIRECT_CALL
    )


def testTheScannerSeesADockerCommandBuiltFromScratch(moduleGenerator):
    """A subprocess reaches the daemon without passing any primitive.

    ``docker stop`` in a browser lifecycle route and ``docker cp``
    writing onto the HOST filesystem both bypass the gateways entirely,
    so a scan that enumerated only primitives reported on a boundary it
    had never looked at.
    """
    listRows = _flistScanSource(moduleGenerator, """
        def fnStopIt(sContainerName):
            subprocess.run(
                ["docker", "stop", sContainerName],
                capture_output=True, text=True,
            )
    """)
    assert len(listRows) == 1, listRows
    assert listRows[0]["sPrimitive"] == "docker stop"
    assert listRows[0]["bMutationCapable"] is True
    assert listRows[0]["sAccess"] == (
        moduleGenerator.S_ACCESS_DIRECT_DOCKER_CLI
    )


def testADockerReadCommandIsRecordedAsARead(moduleGenerator):
    """``docker inspect`` reaches the daemon but changes nothing."""
    listRows = _flistScanSource(moduleGenerator, """
        def fnInspect(sContainerName):
            subprocess.run(["docker", "inspect", sContainerName])
    """)
    assert len(listRows) == 1, listRows
    assert listRows[0]["bMutationCapable"] is False


def testANonDockerSubprocessIsNotRecorded(moduleGenerator):
    """The scan must not sweep in every subprocess in the package."""
    assert _flistScanSource(moduleGenerator, """
        def fnRunGit():
            subprocess.run(["git", "status"], capture_output=True)
    """) == []


def testADockerCommandBoundToALocalNameIsStillSeen(moduleGenerator):
    """``saCommand = [...]`` then ``run(saCommand)`` is the common shape.

    Ten real Docker invocations -- ``rm``, ``tag``, ``exec``, ``stats``
    -- were invisible purely because their argv had a name.
    """
    listRows = _flistScanSource(moduleGenerator, """
        def fnRemoveIt(sContainerName):
            saCommand = ["docker", "rm", sContainerName]
            subprocess.run(saCommand, capture_output=True)
    """)
    assert len(listRows) == 1, listRows
    assert listRows[0]["sPrimitive"] == "docker rm"
    assert listRows[0]["bMutationCapable"] is True


def testAnUnreadableCommandIsDeclaredRatherThanDropped(moduleGenerator):
    """A command the scan cannot follow is counted, not ignored."""
    visitor = moduleGenerator._VisitorCallSites("synthetic.py")
    visitor.fnCollect(ast.parse(textwrap.dedent("""
        def fnRunWhatever(saCommandFromElsewhere):
            subprocess.run(saCommandFromElsewhere, capture_output=True)
    """)))
    assert visitor.listRows == []
    assert len(visitor.listUnresolvedSubprocessSites) == 1, (
        "an opaque subprocess launch was silently dropped"
    )
    assert visitor.listUnresolvedSubprocessSites[0]["sFunction"] == (
        "fnRunWhatever"
    )


def testANameAssignedTwiceIsNotGuessedAt(moduleGenerator):
    """Two candidate values is not a resolution."""
    visitor = moduleGenerator._VisitorCallSites("synthetic.py")
    visitor.fnCollect(ast.parse(textwrap.dedent("""
        def fnAmbiguous(bFlag):
            saCommand = ["docker", "rm", "a"]
            if bFlag:
                saCommand = ["git", "status"]
            subprocess.run(saCommand)
    """)))
    assert visitor.listRows == [], (
        "the scan guessed which of two assignments was live"
    )
    assert len(visitor.listUnresolvedSubprocessSites) == 1


def testTwoReferencesInOneFunctionGetDistinctRows(moduleGenerator):
    """Repeated sites are separate rows with separate classifications."""
    listRows = moduleGenerator._flistNumberOrdinals(_flistScanSource(
        moduleGenerator, """
            def fnTwice(connectionDocker):
                connectionDocker.fnWriteFile("cid", "/a", b"")
                connectionDocker.fnWriteFile("cid", "/b", b"")
        """,
    ))
    assert len(listRows) == 2
    assert len({moduleGenerator.fsRowKey(row) for row in listRows}) == 2


