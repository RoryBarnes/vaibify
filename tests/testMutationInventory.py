def testEveryPublicGatewayMethodIsInTheScopeList(moduleGenerator):
    """Class methods count, which is where the first version was blind.

    The scan can only find references to primitives it knows about, so
    the scope list is the one place the boundary can be narrowed
    without touching a single call site. The first version read a
    module's ``__all__`` and otherwise walked MODULE-LEVEL definitions
    -- and ``dockerConnection.py`` has no ``__all__`` and defines every
    primitive as a method of ``DockerConnection``, so the check passed
    while looking at nothing at all.
    """
    listMissing = []
    for sModule in ("dockerConnection.py", "containerManager.py"):
        pathModule = PATH_REPOSITORY / "vaibify" / "docker" / sModule
        for sName in _flistPublicCallables(pathModule):
            if sName in _SET_GATEWAY_NAMES_OUT_OF_SCOPE:
                continue
            if sName not in moduleGenerator.DICT_PRIMITIVE_ACCESS:
                listMissing.append(f"{sModule}::{sName}")
    assert listMissing == [], (
        "these public gateway callables are not in the inventory's "
        f"scope list, so their references are invisible to it: "
        f"{listMissing}. Add each to DICT_PRIMITIVE_ACCESS with its "
        "access kind, or name it in "
        "_SET_GATEWAY_NAMES_OUT_OF_SCOPE with a reason."
    )


def _flistPublicCallables(pathModule):
    """Return every public function AND public method in a module."""
    treeAst = ast.parse(pathModule.read_text(encoding="utf-8"))
    listNames = []
    for node in ast.walk(treeAst):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and (
            not node.name.startswith("_")
        ):
            listNames.append(node.name)
    return sorted(set(listNames))


# Public gateway callables that do NOT reach a container, each with the
# reason it is out of scope. An allow-list of names, not a pattern: a
# heuristic over names is exactly what let a new class method slip past
# the first version, because a name it did not recognise looked like a
# name it did not need.
_SET_GATEWAY_NAMES_OUT_OF_SCOPE = {
    # Pure argument/flag assembly for a later launch; no daemon call.
    "flistBuildRunArgs",
    "fnMountSecrets",
    # A tarfile entry filter, closed over two integers. It is called by
    # tarfile once per archive member to stamp the container user onto
    # the entry, touches no container and makes no call; it is a nested
    # function rather than a method only because it must capture the
    # resolved uid/gid.
    "finfoStampOwnership",
    # Validation and naming helpers.
    "fnValidateReservationIdOrRaise",
    # Reads that answer about the HOST or the client, not a container.
    "ftProbeNetworkIsolation",
    "read",
    "close",
    "fsResolveDockerHost",
    # Pure text assembly: looks a program up by NAME in the fixed
    # table and substitutes the path literal. It makes no call, and it
    # is module-level rather than a method precisely so the host leg
    # can share the one table instead of growing a second copy.
    "fsRenderBatchedTypedReadProgram",
    # A pure predicate over an exception object. It reads a status code
    # that a daemon call already returned; it makes no call of its own.
    "fbErrorMeansContainerGone",
    # Its weaker sibling: classifies an already-raised error as "the
    # substrate gave no answer" for the poll lanes. Same shape — an
    # isinstance test over an exception object, no daemon call.
    "fbErrorMeansContainerUnreachable",
}
