# The sites the scan cannot resolve, budgeted BY KIND. A DECLARED blind
# spot with a ratchet, not a silence: each one might be a container
# mutation, and the honest position is to say how many the record cannot
# speak for rather than to imply it covers them.
#
# Per-kind, because one number let the two trade against each other: an
# SDK root could go untraceable while an opaque command was resolved,
# and the total would say the blind spot had not grown.
#
# 23 -> 27 on 2026-08-02, and this is the one shape of increase that is
# not lost ground: giving the scanner a real lexical-scope model
# WITHDREW four false resolutions. `_fsRunDetachedCommand(saCommand)`
# and three siblings take their command as a PARAMETER; the old
# module-wide collector borrowed some other function's `saCommand` and
# recorded them as `docker rm` and `docker tag`. One of them runs
# `docker run`. A site the record described wrongly is worse than one
# it admits it cannot read, so these four moved into the blind spot and
# the row count fell 293 -> 289 with them.
# 27 -> 26 on 2026-08-03: the withdrawn host-side director.py held one
# opaque site, ``fnExecuteCommand``'s ``subprocess.Popen(sCommand,
# shell=True)``. Note what that says about the scanner rather than only
# about the count: the most permissive command authority under
# vaibify/gui/ produced NO inventory row, only a blind-spot entry,
# because completeness was keyed on decoding the command instead of on
# the capability. That is the hole plan rule R3 exists to close.
# 26 -> 18 on 2026-08-03: eight of the recorded sites were never
# subprocess launches. ``asyncio.run(...)`` and ``uvicorn.run(...)`` were
# matched because the check read the trailing method name and nothing
# else, which is the same name-based classification the Docker-client
# origin rule was written to end, one primitive over. Launch detection is
# now rooted in a name the scope binds to the subprocess module, so a
# blind spot that had been over-reported by nearly a third is the size it
# always was. Note the direction of the error: the record was pessimistic
# here, which is the safe direction, but eight entries claiming a review
# was owed on code that could not reach a container is still eight
# reviews aimed at fiction.
DICT_UNRESOLVED_BUDGET = {
    "opaque-subprocess-command": 18,
    "untraceable-docker-sdk-root": 12,
}


def testTheScanDeclaresWhatItCannotRead(moduleGenerator):
    """The blind spot is counted per kind, and each may only shrink.

    A boundary that silently drops the commands it cannot parse reports
    a completeness it does not have -- which is exactly how the first
    version of this inventory came to claim 231 sites when there were
    288. Resolving a site (by naming its command literally, by routing
    it through a gateway, or by constructing the Docker client where it
    is used) lowers a number; adding an opaque one raises it and fails
    here.
    """
    dictInventory = moduleGenerator.fdictLoadInventory()
    listUnresolved = moduleGenerator.flistUnresolvedSites()
    dictCounted = collections.Counter(
        dictSite["sBlindSpotKind"] for dictSite in listUnresolved
    )
    assert set(dictCounted) <= set(DICT_UNRESOLVED_BUDGET), (
        f"an unbudgeted blind-spot kind appeared: "
        f"{set(dictCounted) - set(DICT_UNRESOLVED_BUDGET)}"
    )
    for sKind, iBudget in DICT_UNRESOLVED_BUDGET.items():
        iFound = dictCounted.get(sKind, 0)
        assert iFound <= iBudget, (
            f"{iFound} sites of kind {sKind} are unreadable to the scan, "
            f"over the budget of {iBudget}. Any of them could be a "
            f"container mutation: "
            f"{[s for s in listUnresolved if s['sBlindSpotKind'] == sKind]}"
        )
        if iFound < iBudget:
            pytest.fail(
                f"only {iFound} sites of kind {sKind} are now opaque -- "
                f"lower DICT_UNRESOLVED_BUDGET to hold the gain."
            )
    assert dictInventory["iUnresolvedSiteCount"] == len(listUnresolved), (
        "the recorded blind-spot count disagrees with a fresh scan; "
        "regenerate the inventory"
    )


def testTheRecordedBlindSpotCannotDriftFromTheSource(moduleGenerator):
    """Each declared-unreadable site is compared, not just counted.

    The budget above holds the SIZE of the blind spot. It says nothing
    about WHICH sites are in it, so a recorded site's file, function or
    kind could be rewritten by hand and every check stayed green while
    the totals held. That is the same class of defect as the row drift
    check this file already carries, and it matters more once a site
    carries a manual disposition: a disposition bound to a site that
    moved underneath it is a claim about code nobody re-read.

    Kills: comparing the blind spot by count alone.
    """
    dictInventory = moduleGenerator.fdictLoadInventory()
    dictDrift = moduleGenerator.fdictCompareAgainstSource(
        dictInventory, moduleGenerator.flistScanPackage(),
    )
    assert dictDrift["listBlindSpotDrift"] == [], (
        f"the recorded blind spot disagrees with a fresh scan: "
        f"{dictDrift['listBlindSpotDrift']}. Regenerate with "
        f"python tools/generateMutationInventory.py --write"
    )


