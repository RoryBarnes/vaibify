"""The mutation inventory is complete, unique, current, and well-formed.

The inventory (``tests/mutationInventory.json``, generated by
``tools/generateMutationInventory.py``) is the mandatory checkpoint
before any migration onto a single mutation carrier: one row per
reference that can reach a container, so a 280-site surgery is judged
against a record rather than against whoever last read the diff.

A record that can silently fall behind the code is worse than no record,
because it reads as coverage. THE FIRST VERSION OF THIS FILE WAS THAT
RECORD. It compared the inventory against the same scanner that built
it, and that scanner recognised only a direct call -- so 24 primitives
passed as callbacks (``asyncio.to_thread(connection.fnWriteFile, ...)``)
and 25 Docker CLI invocations assembled from scratch were invisible to
both. 21 of the callbacks were mutation-capable, including the
clean-outputs deletion the whole boundary was justified by. An external
review found it; the tests below are what would have.

So the scanner is now checked ADVERSARIALLY, against synthetic sources
containing each shape it must not miss, rather than only against the
tree it was written from. A scan that agrees with itself proves nothing.
"""

import ast
import importlib.util
import pathlib
import textwrap

import pytest


PATH_REPOSITORY = pathlib.Path(__file__).resolve().parent.parent

# The number of rows still awaiting a reviewer's semantic judgement.
# This is a RATCHET: it may only ever be lowered, and lowering it means
# somebody classified those rows. Raising it means new call sites
# shipped unreviewed, which is the state this record exists to make
# visible.
I_UNCLASSIFIED_ROW_BUDGET = 288


def _fmoduleGenerator():
    """Import the inventory generator by path (tools/ is not a package)."""
    pathTool = PATH_REPOSITORY / "tools" / "generateMutationInventory.py"
    spec = importlib.util.spec_from_file_location(
        "generateMutationInventoryUnderTest", pathTool,
    )
    moduleTool = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(moduleTool)
    return moduleTool


@pytest.fixture(scope="module")
def moduleGenerator():
    return _fmoduleGenerator()


def _flistScanSource(moduleGenerator, sSource, sPath="synthetic.py"):
    """Run the scanner over a synthetic module and return its rows."""
    visitor = moduleGenerator._VisitorCallSites(sPath)
    visitor.fnCollect(ast.parse(textwrap.dedent(sSource)))
    return visitor.listRows


