def testTheInventoryMatchesAFreshScanOfTheSource(moduleGenerator):
    """No added, removed, duplicated, edited, or hand-altered row."""
    dictDrift = moduleGenerator.fdictCompareAgainstSource(
        moduleGenerator.fdictLoadInventory(),
        moduleGenerator.flistScanPackage(),
    )
    assert dictDrift["listAdded"] == [], (
        "these container references are not in the inventory, so "
        "nothing decided whether they may reach a container: "
        f"{dictDrift['listAdded']}. Run "
        "`python tools/generateMutationInventory.py --write` and "
        "classify them."
    )
    assert dictDrift["listRemoved"] == [], (
        "the inventory describes references the source no longer has, "
        f"so a reviewer would be reasoning about fiction: "
        f"{dictDrift['listRemoved']}"
    )
    assert dictDrift["listDuplicated"] == [], (
        f"two rows claim the same site, so one is being ignored and "
        f"nobody knows which: {dictDrift['listDuplicated']}"
    )
    assert dictDrift["listEdited"] == [], (
        "these sites CHANGED since they were recorded, so their "
        "classification describes something else and must be re-read: "
        f"{dictDrift['listEdited']}"
    )
    assert dictDrift["listAltered"] == [], (
        "these rows disagree with a fresh scan about a field the "
        "SCANNER owns, so somebody edited a derived value by hand: "
        f"{dictDrift['listAltered']}"
    )
    assert dictDrift["listCountMismatch"] == [], (
        f"the recorded row count is not the number of rows: "
        f"{dictDrift['listCountMismatch']}"
    )


def testTheUnclassifiedBudgetOnlyEverShrinks(moduleGenerator):
    """The semantic review is unfinished, and says so out loud."""
    listUnclassified = moduleGenerator.flistUnclassifiedKeys(
        moduleGenerator.fdictLoadInventory(),
    )
    assert len(listUnclassified) <= I_UNCLASSIFIED_ROW_BUDGET, (
        f"{len(listUnclassified)} inventory rows are unclassified, over "
        f"the budget of {I_UNCLASSIFIED_ROW_BUDGET}. New call sites "
        f"must be classified as they are added, not deferred onto a "
        f"backlog that only grows."
    )
    if len(listUnclassified) < I_UNCLASSIFIED_ROW_BUDGET:
        pytest.fail(
            f"{len(listUnclassified)} rows are now classified, which is "
            f"progress -- lower I_UNCLASSIFIED_ROW_BUDGET to "
            f"{len(listUnclassified)} so the ratchet holds the gain."
        )


def testClassifiedRowsUseTheDeclaredVocabulary(moduleGenerator):
    """A classification must be comparable, and an exclusion explained.

    The ratchet above counts rows still holding the sentinel. On its
    own that is trivially defeated: replace UNCLASSIFIED with an empty
    string, or with prose, and the row counts as classified while
    saying nothing a reviewer could check. Enumerated values make two
    classifications comparable, and an exclusion from the carrier
    without a rationale is how a boundary's exceptions grow unaudited.
    """
    listViolations = moduleGenerator.flistSchemaViolations(
        moduleGenerator.fdictLoadInventory(),
    )
    assert listViolations == [], (
        f"these classified rows do not use the declared vocabulary: "
        f"{listViolations}"
    )


# The subprocess launches whose command the scan cannot read. This is a
# DECLARED blind spot with a ratchet, not a silence: each one might be a
# Docker invocation, and the honest position is to say how many the
# record cannot speak for rather than to imply it covers them.
I_UNRESOLVED_SUBPROCESS_BUDGET = 26


def testTheScanDeclaresWhatItCannotRead(moduleGenerator):
    """The blind spot is counted, and may only shrink.

    A boundary that silently drops the commands it cannot parse reports
    a completeness it does not have -- which is exactly how the first
    version of this inventory came to claim 231 sites when there were
    288. Resolving a site (by naming its command literally, or by
    routing it through a gateway) lowers this number; adding an opaque
    one raises it and fails here.
    """
    dictInventory = moduleGenerator.fdictLoadInventory()
    listUnresolved = moduleGenerator.flistUnresolvedSubprocessSites()
    assert len(listUnresolved) <= I_UNRESOLVED_SUBPROCESS_BUDGET, (
        f"{len(listUnresolved)} subprocess launches build their command "
        f"where the scan cannot read it, over the budget of "
        f"{I_UNRESOLVED_SUBPROCESS_BUDGET}. Any of them could be a "
        f"Docker invocation: {listUnresolved}"
    )
    assert dictInventory["iUnresolvedSubprocessCount"] == len(
        listUnresolved,
    ), (
        "the recorded blind-spot count disagrees with a fresh scan; "
        "regenerate the inventory"
    )
    if len(listUnresolved) < I_UNRESOLVED_SUBPROCESS_BUDGET:
        pytest.fail(
            f"only {len(listUnresolved)} sites are now opaque -- lower "
            f"I_UNRESOLVED_SUBPROCESS_BUDGET to hold the gain."
        )


