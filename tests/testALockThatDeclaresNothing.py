"""A project with no third-party dependency can still reach Level 3.

The Level 3 dependency row once refused every lock with no entry, so a
project that needs only the standard library could never pass. An empty
lock cannot say whether the project needs nothing or nobody locked it,
so the GENERATOR records the first case: when the compile pins nothing,
it writes ``S_NO_DEPENDENCIES_MARKER`` into the lock. The check accepts
a lock with no entry only with that line; an empty file nobody
generated still fails, naming the remedy.

Both legs of the generator are driven -- a host clone compiled in place
and a container repo compiled through staging -- with the compiler
faked to write exactly what uv writes for an empty input (measured).
One test runs the real uv when it is installed.
"""

import shutil
from pathlib import Path
from unittest import mock

import pytest

from tests.testDependencyPinning import (
    _ContainerAnsweringProbes,
    _S_FREEZE,
    _S_VALID_LOCK,
    _ffnFakeRunRecordingStaging,
)
from vaibify.reproducibility.dependencyPinning import (
    S_NO_DEPENDENCIES_MARKER,
    flistVerifyRequirementsLock,
    fnGenerateRequirementsLock,
)
from vaibify.reproducibility.levelGates import fbVerifyDependencyLock


S_MODULE = "vaibify.reproducibility.dependencyPinning"
S_UV_EMPTY_LOCK = (
    "# This file was autogenerated by uv via the following command:\n"
    "#    uv pip compile --generate-hashes requirements.txt -o "
    "requirements.lock\n"
)


def _fnFakeCompileWriting(sLockBody):
    def fnFake(listCommand, cwd, capture_output, text, timeout=None,
               encoding=None):
        (Path(cwd) / "requirements.lock").write_text(sLockBody)
        return mock.Mock(returncode=0, stdout="", stderr="")
    return fnFake


def _fnGenerateOnTheHost(pathRepo, sLockBody):
    with mock.patch(S_MODULE + ".shutil.which", return_value="/u/uv"), \
            mock.patch(S_MODULE + ".subprocess.run",
                       side_effect=_fnFakeCompileWriting(sLockBody)):
        fnGenerateRequirementsLock(str(pathRepo))


@pytest.mark.falsification
def testAGeneratedLockThatPinsNothingPassesTheDependencyRow(tmp_path):
    """Kills: refusing every lock with no entry, marker or not."""
    (tmp_path / "requirements.txt").write_text("")
    _fnGenerateOnTheHost(tmp_path, S_UV_EMPTY_LOCK)
    sLock = (tmp_path / "requirements.lock").read_text()
    assert sLock == S_UV_EMPTY_LOCK + S_NO_DEPENDENCIES_MARKER + "\n"
    assert flistVerifyRequirementsLock(str(tmp_path)) == []
    assert fbVerifyDependencyLock(str(tmp_path)) is True


@pytest.mark.falsification
def testAnEmptyLockNobodyGeneratedStillFailsAndNamesTheRemedy(tmp_path):
    """Kills: accepting any lock with no entry."""
    (tmp_path / "requirements.lock").write_text(S_UV_EMPTY_LOCK)
    listIssues = flistVerifyRequirementsLock(str(tmp_path))
    assert len(listIssues) == 1
    assert "contains no dependency entries" in listIssues[0]
    assert "regenerate the reproducibility envelope" in listIssues[0]
    assert fbVerifyDependencyLock(str(tmp_path)) is False


def testALockThatPinsSomethingIsNeverMarked(tmp_path):
    (tmp_path / "requirements.txt").write_text("click\n")
    _fnGenerateOnTheHost(tmp_path, _S_VALID_LOCK)
    assert (tmp_path / "requirements.lock").read_text() == _S_VALID_LOCK


def testTheMarkerIsWrittenOnceThroughRegenerations(tmp_path):
    (tmp_path / "requirements.txt").write_text("")
    for _ in range(2):
        _fnGenerateOnTheHost(tmp_path, S_UV_EMPTY_LOCK)
    assert (tmp_path / "requirements.lock").read_text().count(
        S_NO_DEPENDENCIES_MARKER) == 1


def testAContainerLockThatPinsNothingIsMarkedOnItsOneWrite(tmp_path):
    (tmp_path / "requirements.txt").write_text("")
    filesRepo = _ContainerAnsweringProbes(tmp_path, "3 12 x86_64", _S_FREEZE)
    with mock.patch(S_MODULE + ".shutil.which", return_value="/u/uv"), \
            mock.patch(S_MODULE + ".subprocess.run",
                       side_effect=_ffnFakeRunRecordingStaging(
                           S_UV_EMPTY_LOCK, {})):
        fnGenerateRequirementsLock(filesRepo)
    assert filesRepo.dictWritten["requirements.lock"] == (
        S_UV_EMPTY_LOCK + S_NO_DEPENDENCIES_MARKER + "\n")


@pytest.mark.skipif(shutil.which("uv") is None,
                    reason="the real-compiler check needs uv on PATH")
def testTheRealCompilerOnAnEmptyInputYieldsALockThatPasses(tmp_path):
    (tmp_path / "requirements.txt").write_text("")
    fnGenerateRequirementsLock(str(tmp_path))
    assert (tmp_path / "requirements.lock").read_text().splitlines()[-1] == (
        S_NO_DEPENDENCIES_MARKER)
    assert fbVerifyDependencyLock(str(tmp_path)) is True
