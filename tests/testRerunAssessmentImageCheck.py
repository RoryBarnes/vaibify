"""The image check (design D2) on figures generated here with Pillow.

Each figure is published, pinned by the real manifest writer, set aside
by ``prepare`` before the rerun deletes it, regenerated by a plot
command, and graded. The expected outcomes are D2's rules: RGBA per
channel with a threshold of 2 levels, supported encodings read from the
file's own bytes, and every failure of the check reading as
insufficient evidence, never as a pass.

The counterexamples are the reviews': 16 inverted pixels in a
1024x1024 image are invisible to a root-mean-square metric, two
palette images with the same indices compare as identical before RGBA
conversion, and a 16-bit PNG opens as 8-bit RGB in Pillow (design fact
23), so a check that trusted Pillow's mode would compare reduced bytes.
"""

import io
import os
import struct
import zlib

import pytest
from PIL import Image

from tests.rerunAssessmentHarness import (
    fdictBuildStep,
    fdictBuildWorkflow,
    fdictFindOutput,
    fdictRunRerunInPython,
    fnPinManifest,
    fnWriteBytes,
)


def _fbaEncode(imageSource, sFormat, **dictOptions):
    """Return an image's encoded bytes."""
    bufferOut = io.BytesIO()
    imageSource.save(bufferOut, format=sFormat, **dictOptions)
    return bufferOut.getvalue()


def _fbaPng16BitRgb(iLowByte):
    """Return a 4x4 16-bit RGB PNG, built by hand; Pillow cannot write one."""
    baRows = b"".join(
        b"\x00" + struct.pack(">HHH", 0x1200 + iLowByte, 0x3400, 0x5600) * 4
        for _ in range(4))

    def fbaChunk(baType, baData):
        return (struct.pack(">I", len(baData)) + baType + baData
                + struct.pack(">I", zlib.crc32(baType + baData) & 0xFFFFFFFF))
    return (b"\x89PNG\r\n\x1a\n"
            + fbaChunk(b"IHDR", struct.pack(">IIBBBBB", 4, 4, 16, 2, 0, 0, 0))
            + fbaChunk(b"IDAT", zlib.compress(baRows))
            + fbaChunk(b"IEND", b""))


def _fbaSquare(iSize, tColor=(200, 180, 160)):
    """Return a uniform RGB PNG of the given side."""
    return _fbaEncode(Image.new("RGB", (iSize, iSize), tColor), "PNG")


def _fbaSquareWithChangedPixels(iSize, iCount, fnChange):
    """Return the uniform square with ``iCount`` pixels changed by fnChange."""
    imageChanged = Image.new("RGB", (iSize, iSize), (200, 180, 160))
    for iPixel in range(iCount):
        tPixel = imageChanged.getpixel((iPixel, 0))
        imageChanged.putpixel((iPixel, 0), fnChange(tPixel))
    return _fbaEncode(imageChanged, "PNG")


def _fdictGradeFigure(tmp_path, sName, baPublished, baRerun, bPlotOnly=False):
    """Publish one figure, regenerate it as baRerun, and return its record."""
    sRoot = str(tmp_path / "repo")
    sSource = str(tmp_path / ("rerun" + os.path.splitext(sName)[1]))
    with open(sSource, "wb") as fileOut:
        fileOut.write(baRerun)
    fnWriteBytes(sRoot, f"StepOne/{sName}", baPublished)
    dictStep = fdictBuildStep(
        "Figures", "StepOne", saPlotCommands=[f"cp {sSource} {sName}"],
        saPlotFiles=[sName], bPlotOnly=bPlotOnly)
    dictWorkflow = fdictBuildWorkflow([dictStep])
    fnPinManifest(sRoot, dictWorkflow)
    dictReport = fdictRunRerunInPython(
        sRoot, str(tmp_path), dictWorkflow)["dictReport"]
    return fdictFindOutput(dictReport, f"StepOne/{sName}"), dictReport


@pytest.mark.falsification
def testSixteenInvertedPixelsAtFullSizeAreNotWithinTheThreshold(tmp_path):
    """The review's counterexample: RMS would call this nearly identical.

    Kills: accepting a figure because few pixels changed.
    """
    dictOutput, dictReport = _fdictGradeFigure(
        tmp_path, "figure.png", _fbaSquare(1024),
        _fbaSquareWithChangedPixels(
            1024, 16, lambda tPixel: tuple(255 - i for i in tPixel)))
    dictImage = dictOutput["dictImageCheck"]
    assert dictImage["bRan"] is True
    assert dictImage["iPixelsChanged"] == 16
    assert dictImage["iLargestLevelChange"] == 145
    assert dictOutput["sOutcome"] == "insufficient evidence"
    assert dictReport["iExitCode"] == 5


@pytest.mark.falsification
def testAOneLevelChangeIsWithinTheThreshold(tmp_path):
    """A rounding-level redraw passes, and is labeled as vaibify's threshold.

    Kills: a threshold of zero, which fails every figure whose bytes move.
    """
    dictOutput, dictReport = _fdictGradeFigure(
        tmp_path, "figure.png", _fbaSquare(1024),
        _fbaSquareWithChangedPixels(
            1024, 40, lambda tPixel: (tPixel[0] + 1,) + tPixel[1:]))
    assert dictOutput["dictImageCheck"]["iLargestLevelChange"] == 1
    assert dictOutput["dictImageCheck"]["iPixelsChanged"] == 40
    assert dictOutput["sOutcome"] == "comparisons passed"
    assert dictOutput["sReason"] == (
        "within vaibify's image-difference threshold (policy v1)")
    assert dictReport["sVerdict"] == "comparisons-passed"


@pytest.mark.falsification
def testPaletteImagesWithTheSameIndicesAndDifferentPalettesDiffer(tmp_path):
    """Indices are not colors; only RGBA conversion sees the change.

    Kills: comparing palette images without converting them to RGBA.
    """
    imageBlack = Image.new("P", (16, 16), 0)
    imageBlack.putpalette([0, 0, 0] * 256)
    imageWhite = Image.new("P", (16, 16), 0)
    imageWhite.putpalette([255, 255, 255] * 256)
    dictOutput, _ = _fdictGradeFigure(
        tmp_path, "figure.png", _fbaEncode(imageBlack, "PNG"),
        _fbaEncode(imageWhite, "PNG"))
    assert dictOutput["dictImageCheck"]["iLargestLevelChange"] == 255
    assert dictOutput["sOutcome"] == "insufficient evidence"


@pytest.mark.falsification
def testPaletteTransparencyIsResolved(tmp_path):
    """The same palette and indices, one transparent: a different figure.

    Kills: comparing palette images without converting them to RGBA.
    """
    imagePalette = Image.new("P", (16, 16), 0)
    imagePalette.putpalette([10, 20, 30] * 256)
    dictOutput, _ = _fdictGradeFigure(
        tmp_path, "figure.png", _fbaEncode(imagePalette, "PNG"),
        _fbaEncode(imagePalette, "PNG", transparency=0))
    assert dictOutput["dictImageCheck"]["iLargestLevelChange"] == 255
    assert dictOutput["sOutcome"] == "insufficient evidence"


@pytest.mark.falsification
def testASixteenBitRgbPngIsNeverReducedToEightBits(tmp_path):
    """Two 16-bit PNGs differing only in the low byte decode as identical RGB.

    Kills: trusting the decoded mode instead of the header's bit depth.
    """
    dictOutput, _ = _fdictGradeFigure(
        tmp_path, "figure.png", _fbaPng16BitRgb(0), _fbaPng16BitRgb(7))
    assert dictOutput["dictImageCheck"]["bRan"] is False
    assert "16-bit samples" in dictOutput["dictImageCheck"]["sReason"]
    assert dictOutput["sOutcome"] == "insufficient evidence"


@pytest.mark.falsification
def testASixteenBitGrayscalePngCannotBeAssessed(tmp_path):
    """A 16-bit grayscale PNG is not a supported encoding, by its header.

    Kills: trusting the decoded mode instead of the header's bit depth.
    """
    imageFirst = Image.new("I;16", (8, 8), 1000)
    imageSecond = Image.new("I;16", (8, 8), 1001)
    dictOutput, _ = _fdictGradeFigure(
        tmp_path, "figure.png", _fbaEncode(imageFirst, "PNG"),
        _fbaEncode(imageSecond, "PNG"))
    assert "16-bit samples" in dictOutput["dictImageCheck"]["sReason"]
    assert dictOutput["sOutcome"] == "insufficient evidence"


@pytest.mark.falsification
def testAFloatingPointTiffCannotBeAssessed(tmp_path):
    """A float TIFF has 32 bits per sample; it is never quantized to compare.

    Kills: dropping the bits-per-sample rule for TIFF.
    """
    dictOutput, _ = _fdictGradeFigure(
        tmp_path, "figure.tiff",
        _fbaEncode(Image.new("F", (8, 8), 0.5), "TIFF"),
        _fbaEncode(Image.new("F", (8, 8), 0.25), "TIFF"))
    assert "32-bit samples" in dictOutput["dictImageCheck"]["sReason"]
    assert dictOutput["sOutcome"] == "insufficient evidence"


@pytest.mark.falsification
def testATwoFrameTiffCannotBeAssessed(tmp_path):
    """Only one frame is compared, so a multi-frame image is not supported.

    Kills: comparing a multi-frame image by its first frame.
    """
    imageBlank = Image.new("L", (8, 8), 0)
    dictOutput, _ = _fdictGradeFigure(
        tmp_path, "figure.tiff",
        _fbaEncode(imageBlank, "TIFF", save_all=True,
                   append_images=[Image.new("L", (8, 8), 0)]),
        _fbaEncode(imageBlank, "TIFF", save_all=True,
                   append_images=[Image.new("L", (8, 8), 255)]))
    assert "2 frames" in dictOutput["dictImageCheck"]["sReason"]
    assert dictOutput["sOutcome"] == "insufficient evidence"


