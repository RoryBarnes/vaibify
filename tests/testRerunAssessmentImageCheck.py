@pytest.mark.falsification
def testAChangedVectorFigureIsInsufficientWithItsRemedy(tmp_path):
    """Vaibify has no assessment for a vector figure whose bytes changed.

    Kills: grading a changed vector figure as an ordinary data file.
    """
    dictOutput, _ = _fdictGradeFigure(
        tmp_path, "figure.svg", b"<svg>a</svg>", b"<svg>b</svg>")
    assert dictOutput["sOutcome"] == "insufficient evidence"
    assert "cannot assess a changed vector figure" in dictOutput["sReason"]
    assert "raster companion" in dictOutput["sReason"]


@pytest.mark.falsification
def testAPlotOnlyStepGetsNoExemption(tmp_path):
    """A step that only draws is graded like any other.

    Kills: exempting the plot section's vector figures.
    """
    dictOutput, dictReport = _fdictGradeFigure(
        tmp_path, "figure.pdf", b"%PDF-1.4 a", b"%PDF-1.4 b", bPlotOnly=True)
