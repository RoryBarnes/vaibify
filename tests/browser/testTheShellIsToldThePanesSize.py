"""The shell must be told the size the pane actually has.

A program that repaints in place -- every agent's live area -- sizes
its frames from the pty's window size, and moves the cursor up by the
number of rows it believes it drew. The pane honours that only if the
two agree. A pane with fewer rows than the shell was told lets the
live area outgrow the screen sooner than the program expects, and its
top rows slide into scrollback where no erase can reach them, so they
are printed a second time. A pane with fewer columns soft-wraps lines
the program counted as one row, and every erase falls short by the
rows it did not count. Both show up as duplicated text, and both would
be this pane's defect rather than the program's.

What is asserted, at open and after each kind of resize:

  - ROWS: the shell's ``stty size`` equals the number of rows the pane
    renders.
  - COLUMNS: a line exactly as wide as the shell was told fits on one
    rendered row, and a line one character wider wraps onto exactly
    two. Together these pin equality in both directions -- a wider pane
    would fit the longer line on one row, a narrower one would wrap the
    shorter.

The expected values come from the pty itself, not from vaibify's own
record of what it sent, so the check cannot be satisfied by the code
under test agreeing with itself. Each resize is confirmed to have
changed the rendered geometry before the probe that depends on it, so
a resize that moved nothing cannot pass vacuously.

The pane is a host project's REAL PTY on this machine; nothing here is
modelled by the browser lane's Docker fake.

Kills (confirmed -- the mutation was applied, this test run, and the
named assertion observed to fail):
  - the ioctl removed from ``_fnApplyPendingResizeAndAcknowledge``, so
    the hub acknowledges a size it never gave the pty -> the shell
    reports a size the pane does not have, at open.
"""

import re
import time

import pytest

from tests.browser.testResizeAndCopyHoldTogether import (
    F_SHELL_DEADLINE_SECONDS,
    _fiVisibleRowCount,
    _fnOpenAHostShell,
    _fnTypeInTheShell,
)


pytestmark = [pytest.mark.browser]

T_VIEWPORT_TALL = (1400, 820)
T_VIEWPORT_SHORT = (1400, 600)
T_VIEWPORT_NARROW_SHORT = (1000, 600)

F_RESIZE_SETTLE_SECONDS = 1.5


def _flistReadRenderedRows(pageDashboard):
    """Return the text of every row the pane renders, top to bottom."""
    return pageDashboard.evaluate(
        """() => Array.from(
            document.querySelectorAll('.xterm-rows > div')
        ).map(el => el.textContent.replace(/\\u00a0/g, ' ').trimEnd())""",
    )


def _fnTypeTheSizeProbe(pageDashboard, sTag):
    """Ask the shell its size, then print lines as wide as it believes.

    The letters are generated by ``tr`` so the typed command itself
    contains no run of them that a reader could mistake for output.
    """
    _fnTypeInTheShell(
        pageDashboard,
        "set -- $(stty size); "
        f"printf 'size-{sTag}=%s,%s\\n' \"$1\" \"$2\"; "
        "printf \"%${2}s\\n\" '' | tr ' ' A; "
        "printf \"%$(( $2 + 1 ))s\\n\" '' | tr ' ' B",
    )


def _ftParseTheProbe(listRows, sTag):
    """Return (rows, columns, A-run lengths, B-run lengths), or None.

    A run is the length of each rendered row made only of that letter,
    after the shell's own report line; None until the B line arrived.
    """
    patternReport = re.compile(rf"^size-{sTag}=(\d+),(\d+)$")
    listReports = [
        (iIndex, patternReport.match(sRow))
        for iIndex, sRow in enumerate(listRows)
        if patternReport.match(sRow)
    ]
    if not listReports:
        return None
    iReport, matchReport = listReports[-1]
    listAfter = listRows[iReport + 1:]
    listARuns = [len(s) for s in listAfter if s and set(s) == {"A"}]
    listBRuns = [len(s) for s in listAfter if s and set(s) == {"B"}]
    if not listBRuns:
        return None
    return (int(matchReport.group(1)), int(matchReport.group(2)),
            listARuns, listBRuns)


def _ftReadTheProbe(pageDashboard, sTag):
    """Wait for the probe's output, then read it once it has settled.

    The second read is what makes a half-painted B line impossible to
    mistake for a whole one.
    """
    fStarted = time.monotonic()
    while _ftParseTheProbe(_flistReadRenderedRows(pageDashboard),
                           sTag) is None:
        assert time.monotonic() - fStarted < F_SHELL_DEADLINE_SECONDS, (
            f"the size probe {sTag} never finished printing. Rendered "
            f"rows: {_flistReadRenderedRows(pageDashboard)[-8:]}"
        )
        pageDashboard.wait_for_timeout(250)
    pageDashboard.wait_for_timeout(500)
    return _ftParseTheProbe(_flistReadRenderedRows(pageDashboard), sTag)


def _fnRequireTheShellAgreesWithThePane(pageDashboard, sTag):
    """Probe the shell and fail unless its size is the pane's size."""
    _fnTypeTheSizeProbe(pageDashboard, sTag)
    iShellRows, iShellColumns, listARuns, listBRuns = _ftReadTheProbe(
        pageDashboard, sTag,
    )
    iPaneRows = _fiVisibleRowCount(pageDashboard)
    assert iShellRows == iPaneRows, (
        f"{sTag}: the shell was told {iShellRows} rows but the pane "
        f"renders {iPaneRows}. A repainting program then overflows the "
        "screen at a height it does not expect, and the rows that "
        "scroll away are printed twice"
    )
    assert listARuns == [iShellColumns], (
        f"{sTag}: a line exactly {iShellColumns} wide, the width the "
        f"shell was told, rendered as rows of {listARuns}. The pane is "
        "narrower than the shell believes, so a program's erase falls "
        "short by every row it did not know was wrapped"
    )
    assert listBRuns == [iShellColumns, 1], (
        f"{sTag}: a line {iShellColumns + 1} wide rendered as rows of "
        f"{listBRuns}, not [{iShellColumns}, 1]. The pane is wider than "
        "the shell believes"
    )


def _fnResizeAndRequireTheGeometryMoved(pageDashboard, tViewport, sWhat):
    """Resize the browser and fail unless the pane's rendering changed."""
    iRowsBefore = _fiVisibleRowCount(pageDashboard)
    dictBoxBefore = pageDashboard.locator(".xterm-screen").bounding_box()
    pageDashboard.set_viewport_size(
        {"width": tViewport[0], "height": tViewport[1]},
    )
    time.sleep(F_RESIZE_SETTLE_SECONDS)
    dictBoxAfter = pageDashboard.locator(".xterm-screen").bounding_box()
    iRowsAfter = _fiVisibleRowCount(pageDashboard)
    bMoved = (iRowsAfter != iRowsBefore
              or abs(dictBoxAfter["width"] - dictBoxBefore["width"]) >= 1)
    assert bMoved, (
        f"{sWhat} did not change the pane's geometry ({iRowsBefore} "
        f"rows, {dictBoxBefore} -> {iRowsAfter} rows, {dictBoxAfter}), "
        "so the probe after it "
        "would prove nothing about a resize"
    )


@pytest.mark.falsification
def test_the_shell_is_told_the_panes_size(pageDashboard, serverHub):
    """At open, after a height change, and after a width change.

    Kills: the ioctl removed from ``_fnApplyPendingResizeAndAcknowledge``
    -> the shell reports a size the pane does not have, at open.
    """
    pageDashboard.set_viewport_size(
        {"width": T_VIEWPORT_TALL[0], "height": T_VIEWPORT_TALL[1]},
    )
    _fnOpenAHostShell(pageDashboard, serverHub)
    time.sleep(F_RESIZE_SETTLE_SECONDS)
    _fnRequireTheShellAgreesWithThePane(pageDashboard, "open")

    _fnResizeAndRequireTheGeometryMoved(
        pageDashboard, T_VIEWPORT_SHORT, "a shorter window",
    )
    _fnRequireTheShellAgreesWithThePane(pageDashboard, "shorter")

    _fnResizeAndRequireTheGeometryMoved(
        pageDashboard, T_VIEWPORT_NARROW_SHORT, "a narrower window",
    )
    _fnRequireTheShellAgreesWithThePane(pageDashboard, "narrower")
