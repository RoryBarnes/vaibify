"""Select the comparison policy, build the plan, render the assessor, re-derive.

The Level 3 rerun is graded by one rendered file,
``.vaibify/rerunAssessment.py``: the current procedure
(``rerunProcedure``), one FROZEN comparison policy, and the assessment
plan this module builds from the workflow, concatenated verbatim. The
project pins it beside ``reproduce.sh``; the dashboard writes vaibify's
own render into a shadow's scratch directory and runs that, never the
repository's copy. Both lanes therefore run the same text for the same
policy and workflow.

The policy is SELECTED, never inherited. Line 2 of a rendered file is
``# vaibify-comparison-policy: <ID>``, and nothing else records it. A
reproduction grades under the recorded ID with vaibify's own module for
it (:data:`DICT_COMPARISON_POLICIES`); an ID this vaibify does not ship
cannot be graded at all, and the reader is told to upgrade. The ID only
ever selects vaibify's code -- it never names a path or a module to
import, and it is matched against a strict pattern first.

Reproduction and eligibility are separate questions: a reproduction
grades under the recorded policy, while the Level 3 rebuild requirement
accepts only an attestation made under :data:`S_CURRENT_COMPARISON_POLICY`.
"""

import json
import posixpath
import re

from vaibify.gui.pipelineUtils import flistComputeAllStepLabels
from vaibify.reproducibility import comparisonPolicyV1, rerunProcedure
from vaibify.reproducibility.manifestPaths import (
    fdictWorkflowTemplateValues,
    flistStepOutputRepoPaths,
    fsToRepoRelative,
)
from vaibify.reproducibility.manifestWriter import (
    fsResolveTestDeclarationPath,
)
from vaibify.reproducibility.rerunPreparation import (
    fdictClassifyRerunPaths,
    flistResolveScratchRepoPaths,
    flistSelectStepsTheRerunExecutes,
    fnRefuseUnsafeClassification,
)


__all__ = [
    "ComparisonPolicyUnknownError",
    "DICT_COMPARISON_POLICIES",
    "I_PLAN_SCHEMA_VERSION",
    "S_COMPARISON_POLICY_V1_SHA256",
    "S_CURRENT_COMPARISON_POLICY",
    "S_RERUN_ASSESSMENT_REPO_PATH",
    "fdictBuildAssessmentPlan",
    "fdictRederiveAssessment",
    "fmoduleSelectComparisonPolicy",
    "fsDescribeUnknownPolicy",
    "fsReadRecordedComparisonPolicy",
    "fsRenderRerunAssessmentScript",
]


class ComparisonPolicyUnknownError(Exception):
    """A comparison policy ID this version of vaibify does not include."""


DICT_COMPARISON_POLICIES = {
    comparisonPolicyV1.S_COMPARISON_POLICY: comparisonPolicyV1,
}
S_CURRENT_COMPARISON_POLICY = comparisonPolicyV1.S_COMPARISON_POLICY
# The bytes of comparisonPolicyV1.py, pinned by
# tests/testRerunAssessmentStructure.py. Before the first release that
# ships the module, an edit updates this in the same commit; after it,
# a change is a new module and a new policy ID.
S_COMPARISON_POLICY_V1_SHA256 = (
    "b78115dfc36cf4cb47fe2b613b5d95bd018d2744d416dcffe104cba936bfbbc4"
)

S_RERUN_ASSESSMENT_REPO_PATH = ".vaibify/rerunAssessment.py"
I_PLAN_SCHEMA_VERSION = 1
S_GENERATED_HEADER = (
    "# Generated by vaibify; do not edit. Regenerate reproduce.sh instead."
)
S_POLICY_HEADER_PREFIX = "# vaibify-comparison-policy: "
_RE_POLICY_HEADER = re.compile(
    r"^# vaibify-comparison-policy: ([a-z0-9-]{1,32})$")

# The runner's test groups, named as invocation sections.
_DICT_GROUP_SECTIONS = {
    "dictIntegrity": "integrity",
    "dictQualitative": "qualitative",
    "dictQuantitative": "quantitative",
    "legacy": "legacy",
}
_T_STANDARD_CATEGORIES = ("integrity", "qualitative", "quantitative")
_T_SECTION_OUTPUT_KEYS = (
    ("data", "saOutputDataFiles"),
    ("plot", "saPlotFiles"),
)


# ----------------------------------------------------------------------
# The policy registry
# ----------------------------------------------------------------------


def fsDescribeUnknownPolicy(sComparisonPolicy):
    """Return the "Could not run" reason for a policy vaibify lacks."""
    return (
        f"this project was assessed under {sComparisonPolicy}, which this "
        "version of vaibify does not include; upgrade vaibify."
    )


def fmoduleSelectComparisonPolicy(sComparisonPolicy):
    """Return vaibify's own module for a policy ID, or raise.

    Raises :class:`ComparisonPolicyUnknownError`, carrying the
    researcher-facing reason, for an ID not in the registry.
    """
    modulePolicy = DICT_COMPARISON_POLICIES.get(sComparisonPolicy)
    if modulePolicy is None:
        raise ComparisonPolicyUnknownError(
            fsDescribeUnknownPolicy(sComparisonPolicy))
    return modulePolicy


def fsReadRecordedComparisonPolicy(sFileText):
    """Return the policy ID line 2 records, None for no header, or raise.

    Only the strict pattern is accepted; a line that begins as the
    header but does not match it raises ``ValueError`` rather than being
    read as "none recorded", because a garbled record is not an absent
    one.
    """
    listLines = (sFileText or "").splitlines()
    if len(listLines) < 2 or not listLines[1].startswith(
            S_POLICY_HEADER_PREFIX.rstrip()):
        return None
    matchHeader = _RE_POLICY_HEADER.match(listLines[1])
    if matchHeader is None:
        raise ValueError(
            "the rendered assessor's policy line is malformed: "
            f"{listLines[1][:80]!r}")
    return matchHeader.group(1)


