def flistNumberInvocations(sStepLabel, sSection, listCommands):
    """Return one invocation ID per non-empty command, in order.

    Empty commands are skipped exactly as ``reproduce.sh`` skips them;
    they would run as a no-op that always exits zero.
    """
    listNonEmpty = [sCommand for sCommand in listCommands or []
                    if (sCommand or "").strip()]
    return [
        rerunProcedure.fsBuildInvocationId(sStepLabel, sSection, iPosition)
        for iPosition in range(1, len(listNonEmpty) + 1)
    ]


def fdictPlanTestGroups(sStepLabel, dictStep):
    """Return section name to invocation IDs, in the runner's group order."""
    from vaibify.gui.workflowManager import fdictResolveTestCommandGroups
    return {
        _DICT_GROUP_SECTIONS[sGroup]: flistNumberInvocations(
            sStepLabel, _DICT_GROUP_SECTIONS[sGroup], listCommands)
        for sGroup, listCommands in fdictResolveTestCommandGroups(
            dictStep).items()
    }


def flistPlanStepOutputs(dictStep, dictTemplateValues, modulePolicy):
    """Return each declared output with its section and its kind.

    Each section resolves through ``flistStepOutputRepoPaths``
    restricted to its own key, the manifest writer's own derivation.
    """
    listOutputs = []
    for sSection, sKey in _T_SECTION_OUTPUT_KEYS:
        for sPath in flistStepOutputRepoPaths(
                dictStep, dictTemplateValues, (sKey,)):
            listOutputs.append({
                "sPath": sPath, "sSection": sSection,
                "sKind": modulePolicy.fsClassifyOutputKind(sPath),
            })
    return listOutputs


def fsPairStandardsWithTestPath(sTestPath, sCategory):
    """Return the standards file a generated test opens, or "".

    The templates pair them by suffix through ``__file__``:
    ``test_quantitative_<step>.py`` reads
    ``quantitative_standards_<step>.json`` beside it, and the legacy
    unsuffixed names pair the same way. A test file not named for its
    category is a custom test, with no standards to expect.
    """
    sBase = posixpath.basename(sTestPath)
    sStem = f"test_{sCategory}"
    if not sBase.startswith(sStem) or not sBase.endswith(".py"):
        return ""
    sSuffix = sBase[len(sStem):-len(".py")]
    if sSuffix and not sSuffix.startswith("_"):
        return ""
    return posixpath.join(
        posixpath.dirname(sTestPath), f"{sCategory}_standards{sSuffix}.json")


def flistPlanStandardSets(dictStep):
    """Return ``{sCategory, sStandardsPath, sTestPath}`` per generated category."""
    dictTests = dictStep.get("dictTests") or {}
    if not isinstance(dictTests, dict):
        return []
    sDirectory = dictStep.get("sDirectory", "") or ""
    listSets = []
    for sCategory in _T_STANDARD_CATEGORIES:
        dictCategory = dictTests.get("dict" + sCategory.capitalize()) or {}
        sFilePath = (dictCategory.get("sFilePath") or ""
                     if isinstance(dictCategory, dict) else "")
        if not sFilePath or "{" in sFilePath:
            continue
        sTestPath = fsResolveTestDeclarationPath(sFilePath, sDirectory)
        sStandardsPath = fsPairStandardsWithTestPath(sTestPath, sCategory)
        if sStandardsPath:
            listSets.append({"sCategory": sCategory,
                             "sStandardsPath": sStandardsPath,
                             "sTestPath": sTestPath})
    return listSets


def fdictPlanOneStep(dictStep, sStepLabel, dictTemplateValues, modulePolicy):
    """Return one executed step's entry in the plan."""
    return {
        "sStepLabel": sStepLabel,
        "sStepDirectory": fsToRepoRelative(dictStep.get("sDirectory") or ""),
        "listDataInvocations": flistNumberInvocations(
            sStepLabel, "data", dictStep.get("saDataCommands")),
        "listPlotInvocations": flistNumberInvocations(
            sStepLabel, "plot", dictStep.get("saPlotCommands")),
        "dictTestGroups": fdictPlanTestGroups(sStepLabel, dictStep),
        "listOutputs": flistPlanStepOutputs(
            dictStep, dictTemplateValues, modulePolicy),
        "listStandardSets": flistPlanStandardSets(dictStep),
    }


def fdictBuildClearingJob(dictWorkflow):
    """Return the clearing job, raising the shadow's own refusals first.

    An ambiguous or unsafe classification raises
    ``RerunPreparationRefusedError``, so a script is never rendered with
    a job the shadow would refuse. Scratch directories are resolved with
    the variables ``reproduce.sh`` gives its commands, then made
    repository-relative.
    """
    from vaibify.reproducibility.reproduceScriptGenerator import (
        S_REPRODUCTION_REPO_ROOT,
    )
    dictClassification = fdictClassifyRerunPaths(dictWorkflow)
    fnRefuseUnsafeClassification(dictClassification)
    return {
        "listProduced": sorted(dictClassification["setProduced"]),
        "listProtected": sorted(dictClassification["setProtected"]),
        "listScratch": flistResolveScratchRepoPaths(
            dictWorkflow, S_REPRODUCTION_REPO_ROOT),
    }


def fdictBuildAssessmentPlan(
    dictWorkflow, sComparisonPolicy=S_CURRENT_COMPARISON_POLICY,
):
    """Return the assessment plan (schema 1) for a workflow and a policy.

    Steps appear in execution order, exactly the set the rerun executes,
    each with the identity of every command it will run.
    """
    from vaibify.reproducibility.rerunVerification import (
        flistCarriedOutputRepoPaths,
    )
    modulePolicy = fmoduleSelectComparisonPolicy(sComparisonPolicy)
    dictClearingJob = fdictBuildClearingJob(dictWorkflow)
    listAllSteps = dictWorkflow.get("listSteps", []) or []
    listLabels = flistComputeAllStepLabels(listAllSteps)
    setExecuted = {id(dictStep) for dictStep in
                   flistSelectStepsTheRerunExecutes(dictWorkflow)}
    dictTemplateValues = fdictWorkflowTemplateValues(dictWorkflow)
    return {
        "iPlanSchemaVersion": I_PLAN_SCHEMA_VERSION,
        "sComparisonPolicy": sComparisonPolicy,
        "dictClearingJob": dictClearingJob,
        "listCarriedPaths": flistCarriedOutputRepoPaths(dictWorkflow),
        "listSteps": [
            fdictPlanOneStep(dictStep, listLabels[iIndex],
                             dictTemplateValues, modulePolicy)
            for iIndex, dictStep in enumerate(listAllSteps)
            if id(dictStep) in setExecuted
        ],
    }


