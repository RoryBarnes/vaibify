def fsReadModuleSource(moduleSource):
    """Return a module's source text, read from its own file."""
    with open(moduleSource.__file__, encoding="utf-8") as fileSource:
        return fileSource.read()


def fsRenderRerunAssessmentScript(dictWorkflow, sComparisonPolicy):
    """Return the rendered assessor for a workflow under one policy.

    Deterministic: the same workflow and policy always render the same
    bytes. The plan's JSON is embedded through ``repr``, which keeps
    every workflow-controlled string a literal.
    """
    modulePolicy = fmoduleSelectComparisonPolicy(sComparisonPolicy)
    dictPlan = fdictBuildAssessmentPlan(dictWorkflow, sComparisonPolicy)
    sPlanJson = json.dumps(dictPlan, sort_keys=True, indent=1)
    return "\n".join([
        S_GENERATED_HEADER,
        S_POLICY_HEADER_PREFIX + sComparisonPolicy,
        fsReadModuleSource(rerunProcedure),
        fsReadModuleSource(modulePolicy),
        f"DICT_ASSESSMENT_PLAN = json.loads({sPlanJson!r})",
        "",
        'if __name__ == "__main__":',
        "    sys.exit(fiRunMain(sys.argv[1:], DICT_ASSESSMENT_PLAN))",
    ]) + "\n"


