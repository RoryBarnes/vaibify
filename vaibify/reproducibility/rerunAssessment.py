def fdictRederiveAssessment(dictReport, dictPlan):
    """Recompute every derived field with vaibify's own policy module.

    Returns ``{bConsistent, listDisagreements}``. A report this vaibify
    cannot re-derive -- an unknown policy, a missing field -- is not
    consistent; the caller reports it as "Could not run: inconsistent
    assessment".
    """
    try:
        modulePolicy = fmoduleSelectComparisonPolicy(
            dictReport.get("sComparisonPolicy"))
        dictRederived = modulePolicy.fdictRederiveReport(dictReport, dictPlan)
    except (ComparisonPolicyUnknownError, KeyError, TypeError, ValueError,
            AttributeError) as error:
        return {"bConsistent": False, "listDisagreements": [
            f"the report could not be re-derived ({type(error).__name__}: "
            f"{error})"]}
    listDisagreements = sorted(
        sKey for sKey in set(dictReport) | set(dictRederived)
        if dictReport.get(sKey) != dictRederived.get(sKey))
    return {"bConsistent": not listDisagreements,
            "listDisagreements": listDisagreements}
